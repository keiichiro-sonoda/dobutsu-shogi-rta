#!/bin/bash
# run_time.sh と run_retreat.sh が, 回す前に見る止める条件 (source して使う)
#
# 一致の検査は (e)・(f) で外れたが, 外れたのは正解の取り方 (cls は到達局面にしか種類を持たない) だった.
# 止めたあとに, (e)・(f) の正解を「候補をいまの生成器に通して 0 が返るか」に替えた (README の
# 「止めたあとに直した検査」). 替えたあとの止める条件:
#   1. logs/verify.txt の (a)〜(d) が全部 0 (候補の列, 前任の多重集合, 絞った版にキャッチ局面が残らない)
#   2. logs/diag.txt で, 捨てた候補のうち生成器でキャッチ局面でないもの ＋ 残した候補のうち生成器でキャッチ局面のもの が 0
#   3. A が2マス以上の盤が 0 (q も鏡像も). 出たら計時の前に報告する
check_verify() {
    local v="$1/logs/verify.txt" g="$1/logs/diag.txt" k
    for k in '(a) 分類する版の候補の列が素朴な版と違った q: 0' \
        '(b) 絞った版の候補の列が, 捨てない候補の列と違った q: 0' \
        '(c) 前任の多重集合が素朴な版と違った q: 0' \
        '(d) 絞った版の候補でキャッチ局面を理由に捨てた候補: 0'; do
        if ! grep -qxF "$k" "$v"; then
            echo "!!! 一致の検査が通っていないので測らない (止める条件): $k" >&2
            return 1
        fi
    done
    if ! grep -qxF '捨てた候補のうち生成器でキャッチ局面でないもの ＋ 残した候補のうち生成器でキャッチ局面のもの: 0' "$g" ||
        ! grep -qxF 'diag の終了コード: 0' "$g"; then
        echo "!!! 候補ごとの判定が生成器と食い違ったので測らない (止める条件)" >&2
        return 1
    fi
    if ! grep -qxF 'A が2マス以上の盤: q 0 / 鏡像 0' "$v"; then
        echo "!!! A が2マス以上の盤があったので測らない (計時の前に報告する)" >&2
        return 1
    fi
}
